// Done-predicates of Emerald's main-plot gets (Emerald.md, "Step predicates for the read-only adapter").
// Class rule: BLOCKING only when vanilla forces the get (a scene or gate) or needs it by the end game;
// when in doubt REPORTED. A forced REPORTED get costs only a hint that moves on a little early; a
// skippable BLOCKING get would freeze the main-story-index for good.

#define FLAG_P(flag)          {STORY_PRED_FLAG, flag, 0}
#define EITHER_P(flagA, flagB) {STORY_PRED_ANY_FLAG, flagA, flagB}
#define VAR_P(var, minValue)  {STORY_PRED_VAR_GE, var, minValue}
#define NO_STATE_P            {STORY_PRED_ALWAYS, 0, 0}

#define GET(cls, pred) {cls, pred}
#define ITEM(kind, ordinal, cls, pred) {kind, ordinal, {cls, pred}}

struct PlotGetEntry
{
    u8 kind;
    u8 ordinal;
    struct PlotGetDesc desc;
};

