// Hardcoded Emerald tile roles (design.md, "Development approach", stage 2). Which places go in
// which county is in Emerald.md; positions inside a county are placeholders nudged toward Hoenn.

#define NO_TILE 0xFF

// Local tile (0-4, 0-3) inside a county.
#define T(lx, ly) ((lx) + (ly) * COUNTY_TILES_W)

#define REV5(r) ((((r) & 1) << 4) | (((r) & 2) << 2) | ((r) & 4) | (((r) & 8) >> 2) | (((r) & 16) >> 4))

// Four rows of five route flags written as binary literals, left tile first.
#define ROUTES(r0, r1, r2, r3) \
    (REV5(r0) | REV5(r1) << 5 | REV5(r2) << 10 | REV5(r3) << 15)

#define SPECIAL(lx, ly, sec) {T(lx, ly), sec}

struct SpecialTile
{
    u8 tile;
    u8 mapSec;
};

